// Refreshes src/catalog.js: every make and model CarGurus knows, with the ids its
// search takes (Ford = "m2", F-150 = "d337"), for the "Search the U.S." screen.
// Run now and then (new models each year): node scripts/update-catalog.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "catalog.js");
const PICKER = "https://www.cargurus.com/Cars/getCarPickerReferenceDataAJAX.action?forPriceAnalysis=false&showInactive=false&newCarYear=2026&quotableCarsOnly=false&carsWithRegressionOnly=false&localeCountryCarsOnly=true";

// Plain requests (CarGurus refuses ones dressed up as a browser). One has the names,
// the other says which models are popular.
const get = async (url) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`CarGurus answered HTTP ${r.status} for ${url}`);
  return r.json();
};
const named = (await get(PICKER + "&outputFormat=REACT")).allMakerModels.makers;
await new Promise((r) => setTimeout(r, 1500));
const plain = (await get(PICKER)).allMakerModels;

const makes = named.map((m) => {
  const popular = new Set((plain[m.id]?.popular || []).map((x) => x.modelId));
  return {
    id: m.id, name: m.name, popular: !!m.popular,
    models: m.models.map((x) => ({ id: x.id, name: x.name, ...(popular.has(x.id) ? { popular: true } : {}) }))
      .sort((a, b) => a.name.localeCompare(b.name, "en", { numeric: true })),
  };
}).filter((m) => /^m\d+$/.test(m.id) && m.models.length).sort((a, b) => a.name.localeCompare(b.name));

fs.writeFileSync(OUT, `// Generated by scripts/update-catalog.mjs on ${new Date().toISOString().slice(0, 10)}: CarGurus' makes and models
// with the ids its search takes. Don't edit by hand; run the script again.
export const CATALOG = ${JSON.stringify(makes)};
`);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${makes.length} makes, ${makes.reduce((n, m) => n + m.models.length, 0)} models (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
