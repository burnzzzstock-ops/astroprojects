// Refreshes src/usgeo.js from the free `zipcodes` table (offline):
//   STATES: each state's center ZIP and the radius that covers it, so "search Texas"
//           becomes one CarGurus search (center + radius) with the cars kept to TX;
//   ZIP3:   the middle of each 3-digit ZIP area, so the browser can measure how far a
//           car is from the store (for shipping) without the 3 MB ZIP table.
// Run: node scripts/update-geo.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import zipcodes from "zipcodes";

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "usgeo.js");
const NAMES = {
  AL: "Alabama", AK: "Alaska", AZ: "Arizona", AR: "Arkansas", CA: "California", CO: "Colorado", CT: "Connecticut",
  DE: "Delaware", DC: "Washington, D.C.", FL: "Florida", GA: "Georgia", HI: "Hawaii", ID: "Idaho", IL: "Illinois",
  IN: "Indiana", IA: "Iowa", KS: "Kansas", KY: "Kentucky", LA: "Louisiana", ME: "Maine", MD: "Maryland",
  MA: "Massachusetts", MI: "Michigan", MN: "Minnesota", MS: "Mississippi", MO: "Missouri", MT: "Montana",
  NE: "Nebraska", NV: "Nevada", NH: "New Hampshire", NJ: "New Jersey", NM: "New Mexico", NY: "New York",
  NC: "North Carolina", ND: "North Dakota", OH: "Ohio", OK: "Oklahoma", OR: "Oregon", PA: "Pennsylvania",
  RI: "Rhode Island", SC: "South Carolina", SD: "South Dakota", TN: "Tennessee", TX: "Texas", UT: "Utah",
  VT: "Vermont", VA: "Virginia", WA: "Washington", WV: "West Virginia", WI: "Wisconsin", WY: "Wyoming",
};

const R = 3958.8;
const rad = (d) => (d * Math.PI) / 180;
const miles = (a, b) => {
  const h = Math.sin(rad(b.lat - a.lat) / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(rad(b.lon - a.lon) / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
};

const zips = Object.values(zipcodes.codes)
  .filter((z) => NAMES[z.state] && /^\d{5}$/.test(z.zip) && Number.isFinite(z.latitude) && Number.isFinite(z.longitude))
  .map((z) => ({ zip: z.zip, state: z.state, lat: z.latitude, lon: z.longitude }));

const STATES = {};
for (const code of Object.keys(NAMES)) {
  const own = zips.filter((z) => z.state === code);
  const mid = { lat: own.reduce((s, z) => s + z.lat, 0) / own.length, lon: own.reduce((s, z) => s + z.lon, 0) / own.length };
  const center = own.reduce((best, z) => (miles(z, mid) < miles(best, mid) ? z : best));
  const reach = Math.max(...own.map((z) => miles(center, z)));
  STATES[code] = { name: NAMES[code], zip: center.zip, lat: +center.lat.toFixed(3), lon: +center.lon.toFixed(3), radius: Math.ceil((reach + 10) / 10) * 10 };
}

const areas = new Map();
for (const z of zips) {
  const a = areas.get(z.zip.slice(0, 3)) || { lat: 0, lon: 0, n: 0 };
  a.lat += z.lat; a.lon += z.lon; a.n++;
  areas.set(z.zip.slice(0, 3), a);
}
const ZIP3 = Object.fromEntries([...areas].sort().map(([k, a]) => [k, [+(a.lat / a.n).toFixed(2), +(a.lon / a.n).toFixed(2)]]));

fs.writeFileSync(OUT, `// Generated by scripts/update-geo.mjs from the free \`zipcodes\` table. Don't edit by hand.
// STATES: center ZIP (and its lat/lon) + the radius in miles that covers the whole state.
// ZIP3: the middle [lat, lon] of each 3-digit ZIP area, for rough distances in the browser.
export const STATES = ${JSON.stringify(STATES)};
export const ZIP3 = ${JSON.stringify(ZIP3)};
`);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${Object.keys(STATES).length} states, ${Object.keys(ZIP3).length} ZIP areas (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
for (const c of ["TX", "MS", "RI", "AK", "FL", "CA"]) console.log(`  ${c}: center ${STATES[c].zip}, radius ${STATES[c].radius} mi`);
